/**
 * Agent overlay: the complete `~/.omp/agent` tree a variant trial runs with. Evolution owns
 * prompts/rules/skills/agents/extensions and non-routing settings; the launch owns the fixed
 * executor (model routing, retry) so every comparison runs the same model.
 */
import * as fs from "node:fs/promises";
import * as path from "node:path";
import { isRecord } from "@oh-my-pi/pi-utils/type-guards";
import { assertNoHostCredentialValues, referencedEnvNamesFromText } from "./models-yaml";

/**
 * Built-in omp model roles, frozen locally: importing the coding-agent role registry drags its whole
 * source graph into this package's type-check. `evo-runner.test.ts` pins this list to the live registry.
 */
export const BUILTIN_MODEL_ROLES: readonly string[] = Object.freeze([
	"default",
	"smol",
	"slow",
	"vision",
	"plan",
	"commit",
	"tiny",
	"memory",
	"task",
	"advisor",
	"image",
	"web",
	"speech",
	"dictation",
	"judge",
]);

/** Settings keys evolution may never set; the executor owns them. */
export const RESERVED_EXECUTOR_KEYS = ["modelRoles", "enabledModels", "modelProviderOrder", "retry"] as const;

export interface ExecutorSpec {
	/** Fixed `provider/model` for every role. */
	model: string;
	thinking: string;
	/** Benchmark toggles applied before explicit settings. */
	webSearch: boolean;
	findTool: boolean;
	/** Explicit `--setting` overrides (dotted key to value), applied last. */
	settings: Readonly<Record<string, unknown>>;
}

function sha256(text: string): string {
	return new Bun.CryptoHasher("sha256").update(text).digest("hex");
}

function setDotted(tree: Record<string, unknown>, dotted: string, value: unknown): void {
	let node = tree;
	const parts = dotted.split(".");
	for (const part of parts.slice(0, -1)) {
		const next = node[part] ?? {};
		if (!isRecord(next)) throw new Error(`setting '${dotted}' conflicts with a scalar parent`);
		node[part] = next;
		node = next;
	}
	node[parts[parts.length - 1]] = value;
}

/** Roles the executor pins: every built-in role plus any role the variant defined. */
function roleNames(tree: Record<string, unknown>): string[] {
	const defined = isRecord(tree.modelRoles) ? Object.keys(tree.modelRoles) : [];
	return [...new Set([...BUILTIN_MODEL_ROLES, ...defined])].sort();
}

/** The routing fields the executor owns; hashing these identifies the executor independent of the variant. */
export function executorFields(tree: Record<string, unknown>, spec: ExecutorSpec): Record<string, unknown> {
	const selector = `${spec.model}:${spec.thinking}`;
	return {
		modelRoles: Object.fromEntries(roleNames(tree).map(role => [role, selector])),
		enabledModels: [spec.model],
		defaultThinkingLevel: spec.thinking,
	};
}

/** JSON with object keys sorted recursively, so equal values always serialize identically. */
export function canonicalJson(value: unknown): string {
	if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
	if (isRecord(value)) {
		return `{${Object.keys(value)
			.sort()
			.map(key => `${JSON.stringify(key)}:${canonicalJson(value[key])}`)
			.join(",")}}`;
	}
	return JSON.stringify(value) ?? "null";
}

/** Hash of everything the executor owns: role selectors, thinking, benchmark toggles, explicit settings. */
export function executorConfigHash(spec: ExecutorSpec): string {
	return sha256(
		canonicalJson({
			...executorFields({}, spec),
			model: spec.model,
			thinking: spec.thinking,
			webSearch: spec.webSearch,
			findTool: spec.findTool,
			settings: spec.settings,
		}),
	);
}

/** Merge a variant `config.yml` (may be absent) with the executor; explicit settings win. */
export function mergeOverlayConfig(variantYaml: string | null, spec: ExecutorSpec): string {
	const parsed: unknown = variantYaml === null ? {} : Bun.YAML.parse(variantYaml);
	if (parsed !== null && !isRecord(parsed)) throw new Error("variant config.yml must be a YAML mapping");
	const tree: Record<string, unknown> = { ...parsed };
	const roles = executorFields(tree, spec);
	for (const key of RESERVED_EXECUTOR_KEYS) delete tree[key];
	delete tree.defaultThinkingLevel;
	Object.assign(tree, roles);
	setDotted(tree, "web_search.enabled", spec.webSearch);
	setDotted(tree, "find.enabled", spec.findTool);
	for (const [dotted, value] of Object.entries(spec.settings)) setDotted(tree, dotted, value);
	return `# Generated by metaharness evo overlay.\n${Bun.YAML.stringify(tree, null, 2)}\n`;
}

export interface StagedOverlay {
	dir: string;
	stagedConfigHash: string;
	executorConfigHash: string;
}

export interface StageOptions {
	variantConfigDir: string;
	dest: string;
	spec: ExecutorSpec;
	/** Fixed container-safe models.yml. */
	modelsYaml: string;
	/** Values that must never appear in the staged tree (forwarded secrets). */
	secretValues?: readonly string[];
}

async function copyTree(src: string, dest: string): Promise<void> {
	await fs.mkdir(dest, { recursive: true });
	for (const entry of await fs.readdir(src, { withFileTypes: true })) {
		const from = path.join(src, entry.name);
		const to = path.join(dest, entry.name);
		if (entry.isDirectory()) await copyTree(from, to);
		else if (entry.isFile()) await fs.copyFile(from, to);
		else throw new Error(`variant snapshot contains a non-regular file: ${from}`);
	}
}

/** Materialize `dest` as variant files + merged `config.yml` + fixed `models.yml`. */
export async function stageAgentOverlay(opts: StageOptions): Promise<StagedOverlay> {
	const modelsText = await Bun.file(opts.modelsYaml)
		.text()
		.catch(() => {
			throw new Error(`--models-yaml not readable: ${opts.modelsYaml}`);
		});
	referencedEnvNamesFromText(modelsText);
	assertNoHostCredentialValues(modelsText, opts.secretValues ?? []);
	const configFile = Bun.file(path.join(opts.variantConfigDir, "config.yml"));
	const variantYaml = (await configFile.exists()) ? await configFile.text() : null;
	const merged = mergeOverlayConfig(variantYaml, opts.spec);
	await fs.rm(opts.dest, { recursive: true, force: true });
	await copyTree(opts.variantConfigDir, opts.dest);
	await fs.rm(path.join(opts.dest, "config.yml"), { force: true });
	await Bun.write(path.join(opts.dest, "config.yml"), merged);
	await Bun.write(path.join(opts.dest, "models.yml"), modelsText);
	const stagedConfigHash = sha256(merged);
	const executor = executorConfigHash(opts.spec);
	await Bun.write(
		path.join(path.dirname(opts.dest), "overlay-meta.json"),
		JSON.stringify({ stagedConfigHash, executorConfigHash: executor }, null, "\t"),
	);
	return { dir: opts.dest, stagedConfigHash, executorConfigHash: executor };
}
